#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_operation_has_a_description() {
        for name in crate::dispatch::OPERATIONS {
            assert!(describe(name).is_some(), "{name} has no description");
        }
    }

    #[test]
    fn every_description_is_complete_and_short() {
        let mut names = std::collections::HashSet::new();
        for d in COMMANDS {
            assert!(names.insert(d.name), "{} is described twice", d.name);
            for (field, text) in [
                ("summary", d.summary),
                ("when", d.when),
                ("returns", d.returns),
                ("example", d.example),
            ] {
                assert!(!text.is_empty(), "{}: empty {field}", d.name);
            }
            assert!(
                d.example.starts_with(&format!("codix {}", d.name)),
                "{}: the example runs another command",
                d.name
            );
            let words = d.details().split_whitespace().count();
            assert!(words <= 80, "{}: {words} words", d.name);
        }
    }
}
