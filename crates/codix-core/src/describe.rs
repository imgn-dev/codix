//! The canonical description of every command, written once and used by
//! `--help`, `codix help`, the MCP tool list and the generated docs.
//!
//! Descriptions are short on purpose: an agent reads them in every session.

use std::fmt::Write as _;

use serde::Serialize;

use crate::capabilities::Tier;

/// One command's description.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
pub struct Description {
    /// The command, such as `find` or `daemon start`.
    pub name: &'static str,
    /// What it does, in one line.
    pub summary: &'static str,
    /// When to use it, and what to prefer it over.
    pub when: &'static str,
    /// What it returns.
    pub returns: &'static str,
    /// The language support it needs; `None` when it works on any file.
    pub tier: Option<Tier>,
    /// One example.
    pub example: &'static str,
}

impl Description {
    /// The description as `--help` and `codix help` show it, after the
    /// summary.
    pub fn details(&self) -> String {
        let tier = match self.tier {
            Some(Tier::Symbols) => "\nNeeds: tier 1 (symbols); see `codix capabilities`.",
            Some(Tier::Scopes) => "\nNeeds: tier 2 (scopes); see `codix capabilities`.",
            Some(Tier::Search | Tier::NotInBuild) => "\nNeeds: any indexed text file.",
            None => "",
        };
        format!(
            "{}\n\nWhen: {}\nReturns: {}{tier}",
            self.summary, self.when, self.returns
        )
    }
}

/// The first line of a file `init --agent-docs` wrote, which lets it
/// overwrite that file and nothing else.
pub const AGENT_DOCS_MARKER: &str =
    "<!-- Generated by `codix init --agent-docs`; run it again rather than edit this file. -->";

/// `docs/commands.md`: every description, for people.
pub fn markdown() -> String {
    let mut out = String::from(
        "# codix commands\n\n\
         Generated from `crates/codix-core/src/describe.rs`, the descriptions `--help` and \
         MCP show; `CODIX_BLESS=1 cargo test -p codix-cli --test describe` rewrites it.\n",
    );
    for d in COMMANDS {
        let needs = match d.tier {
            Some(Tier::Symbols) => "\n- **Needs:** tier 1 (symbols)",
            Some(Tier::Scopes) => "\n- **Needs:** tier 2 (scopes)",
            Some(Tier::Search | Tier::NotInBuild) => "\n- **Needs:** any indexed text file",
            None => "",
        };
        // Writing to a String cannot fail.
        let _ = write!(
            out,
            "\n## `codix {}`\n\n{}\n\n- **When:** {}\n- **Returns:** {}{needs}\n\n```\n{}\n```\n",
            d.name, d.summary, d.when, d.returns, d.example
        );
    }
    out
}

/// The workflow guide `init --agent-docs` writes, for an agent's
/// instructions.
pub fn agent_guide() -> String {
    let mut out = format!(
        "{AGENT_DOCS_MARKER}\n\
         # Navigating this project with codix\n\n\
         This project has a codix index. To find and read code, prefer these commands to grep \
         and to reading whole files:\n\n"
    );
    for d in ["find", "def", "outline", "show", "grep"]
        .iter()
        .filter_map(|name| describe(name))
    {
        let _ = writeln!(out, "- `{}`: {} {}", d.example, d.summary, d.when);
    }
    out.push_str(
        "\nResults carry symbol IDs, such as `java:src/A.java::A.run#3f2a`, that `def` and \
         `show` accept. Add `--json` for structured output. `codix help <command>` describes \
         any command, and `codix capabilities` what each language supports.\n",
    );
    out
}

/// The description of `name`, if it is a command.
pub fn describe(name: &str) -> Option<&'static Description> {
    COMMANDS.iter().find(|d| d.name == name)
}

